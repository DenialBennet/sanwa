begin;
create table public.admin_users (user_id uuid primary key references auth.users(id) on delete cascade);
alter table public.admin_users enable row level security;
revoke all on public.admin_users from anon, authenticated;
grant select on public.admin_users to authenticated;
create policy "Read own admin membership" on public.admin_users for select to authenticated using (user_id = (select auth.uid()));
create function public.is_admin() returns boolean language sql stable security definer set search_path = ''
as $$ select exists(select 1 from public.admin_users where user_id = (select auth.uid())); $$;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;
create table public.vessel_schedules (
  id bigint generated by default as identity primary key,
  kapal text not null check (char_length(trim(kapal)) between 1 and 150),
  voy text not null check (char_length(trim(voy)) between 1 and 100),
  closing timestamptz not null,
  etd_sub date not null,
  is_full boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint closing_before_departure check ((closing at time zone 'Asia/Jakarta')::date <= etd_sub)
);
create index vessel_schedules_etd_idx on public.vessel_schedules(etd_sub);
create index vessel_schedules_closing_idx on public.vessel_schedules(closing);
alter table public.vessel_schedules enable row level security;
revoke all on public.vessel_schedules from anon,authenticated;
grant select on public.vessel_schedules to anon,authenticated;
grant insert,update,delete on public.vessel_schedules to authenticated;
grant usage,select on sequence public.vessel_schedules_id_seq to authenticated;
create policy "Public schedule reading" on public.vessel_schedules for select to anon,authenticated using (true);
create policy "Admin schedule insertion" on public.vessel_schedules for insert to authenticated with check ((select public.is_admin()));
create policy "Admin schedule updates" on public.vessel_schedules for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
create policy "Admin schedule deletion" on public.vessel_schedules for delete to authenticated using ((select public.is_admin()));
create function public.set_schedule_updated_at() returns trigger language plpgsql set search_path = ''
as $$ begin new.updated_at = now(); return new; end; $$;
create trigger schedule_updated_at before update on public.vessel_schedules for each row execute function public.set_schedule_updated_at();
commit;
